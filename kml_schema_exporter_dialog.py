import os
from qgis.PyQt import uic
from qgis.PyQt.QtWidgets import (QDialog, QTableWidgetItem, QFileDialog,
                                 QMessageBox, QComboBox)
from qgis.core import QgsProject, QgsMapLayer
from qgis.PyQt.QtCore import Qt
from qgis.core import QgsProject, QgsMapLayer, QgsWkbTypes

FORM_CLASS, _ = uic.loadUiType(os.path.join(
    os.path.dirname(__file__), 'kml_schema_exporter_dialog_base.ui'))


class KmlExporterDialog(QDialog, FORM_CLASS):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.setupUi(self)

        # Llenar el combo con las capas vectoriales cargadas
        self.populate_layer_combo()

        # Señales
        self.mMapLayerComboBox.currentIndexChanged.connect(
            lambda _: self.on_layer_changed()
        )
        self.btnBrowseOutput.clicked.connect(self.select_output_path)
        self.btnExport.clicked.connect(self.run_export)
        self.tableFieldMapping.itemChanged.connect(self.on_table_item_changed)
        self.btnToggleIncluirTodo.clicked.connect(self.toggle_incluir_todo)
        QgsProject.instance().layersAdded.connect(self.populate_layer_combo)
        QgsProject.instance().layersRemoved.connect(self.populate_layer_combo)
        self.checkBoxExportarPorLotes.toggled.connect(self.on_batch_mode_toggled)
        self.on_batch_mode_toggled(False)  # estado inicial
        self.checkBoxAgruparCarpetas.toggled.connect(self.on_group_mode_toggled)
        self.checkBoxCapaReferencia.toggled.connect(self.on_reference_toggled)
        self.comboCapaReferencia.currentIndexChanged.connect(
            lambda _: self.populate_reference_fields()
        )
        self.on_group_mode_toggled(False)
        self.checkBoxIconosClasicos.setChecked(True)

        # Poblar con la capa inicial si ya hay una seleccionada
        self.populate_field_table(self._get_current_layer())
        self.tableFieldMapping.setFocusPolicy(Qt.NoFocus)

    def populate_layer_combo(self, *args):
        current_layer_id = self.mMapLayerComboBox.currentData()
        self.mMapLayerComboBox.blockSignals(True)
        self.mMapLayerComboBox.clear()
        layers = QgsProject.instance().mapLayers().values()
        index_to_select = 0

        for i, layer in enumerate(layers):
            if layer.type() == QgsMapLayer.VectorLayer:
                self.mMapLayerComboBox.addItem(layer.name(), layer.id())
                if layer.id() == current_layer_id:
                    index_to_select = self.mMapLayerComboBox.count() - 1

        self.mMapLayerComboBox.setCurrentIndex(index_to_select)
        self.mMapLayerComboBox.blockSignals(False)
        self.populate_field_table(self._get_current_layer())

    def on_batch_mode_toggled(self, checked):
        """Alterna la UI entre modo normal (un archivo) y modo por lotes (varios)."""
        self.groupBoxCapasExtra.setEnabled(not checked)
        self.comboCampoLotes.setVisible(checked)
        self.labelCampoLotes.setVisible(checked)
        self.lineEditDocumentName.setEnabled(not checked)
        self.lineEditFolderName.setEnabled(not checked)

        if checked:
            self.btnBrowseOutput.setText("Elegir carpeta...")
            self.lineEditOutputPath.setPlaceholderText("Carpeta donde se guardarán los .kml")
        else:
            self.btnBrowseOutput.setText("...")
            self.lineEditOutputPath.setPlaceholderText("")

        self.lineEditOutputPath.clear()

    def on_group_mode_toggled(self, checked):
        """Habilita el selector de campo y la opción de capa de referencia."""
        self.comboCampoCarpetas.setEnabled(checked)
        self.checkBoxCapaReferencia.setEnabled(checked)
        if not checked:
            self.checkBoxCapaReferencia.setChecked(False)

    def on_reference_toggled(self, checked):
        self.comboCapaReferencia.setEnabled(checked)
        self.comboCampoReferencia.setEnabled(checked)
        if checked:
            self.populate_reference_layers()

    def populate_reference_layers(self):
        self.comboCapaReferencia.blockSignals(True)
        self.comboCapaReferencia.clear()
        for lyr in QgsProject.instance().mapLayers().values():
            if lyr.type() == QgsMapLayer.VectorLayer:
                self.comboCapaReferencia.addItem(lyr.name(), lyr.id())
        self.comboCapaReferencia.blockSignals(False)
        self.populate_reference_fields()

    def populate_reference_fields(self):
        self.comboCampoReferencia.clear()
        layer_id = self.comboCapaReferencia.currentData()
        lyr = QgsProject.instance().mapLayer(layer_id) if layer_id else None
        if lyr is None:
            return
        for field in lyr.fields():
            self.comboCampoReferencia.addItem(field.name())

    def populate_extra_layers_table(self):
        """Una fila por capa vectorial (excepto la capa actual)."""
        table = self.tableCapasExtra
        table.blockSignals(True)
        table.setRowCount(0)
        table.setColumnCount(3)
        table.setHorizontalHeaderLabels(["Incluir", "Capa", "Campo nombre"])
        current = self._get_current_layer()
        row = 0
        for lyr in QgsProject.instance().mapLayers().values():
            if lyr.type() != QgsMapLayer.VectorLayer:
                continue
            if current is not None and lyr.id() == current.id():
                continue
            table.insertRow(row)

            chk = QTableWidgetItem()
            chk.setFlags(Qt.ItemIsUserCheckable | Qt.ItemIsEnabled)
            chk.setCheckState(Qt.Unchecked)
            chk.setData(Qt.UserRole, lyr.id())
            table.setItem(row, 0, chk)

            name_item = QTableWidgetItem(lyr.name())
            name_item.setFlags(name_item.flags() & ~Qt.ItemIsEditable)
            table.setItem(row, 1, name_item)

            combo = QComboBox()
            combo.addItem("(nombre de la capa)", None)
            for f in lyr.fields():
                combo.addItem(f.name(), f.name())
            table.setCellWidget(row, 2, combo)
            row += 1
        table.resizeColumnsToContents()
        table.blockSignals(False)

    def get_extra_layers(self):
        """Devuelve [(capa, campo_nombre_o_None), ...] de las filas marcadas."""
        result = []
        table = self.tableCapasExtra
        for row in range(table.rowCount()):
            chk = table.item(row, 0)
            if chk is None or chk.checkState() != Qt.Checked:
                continue
            lyr = QgsProject.instance().mapLayer(chk.data(Qt.UserRole))
            if lyr is None:
                continue
            combo = table.cellWidget(row, 2)
            result.append((lyr, combo.currentData() if combo is not None else None))
        return result

    def on_layer_changed(self):
        """Actualiza la tabla cuando cambia la capa seleccionada."""
        layer = self._get_current_layer()
        self.populate_field_table(layer)

    def _get_current_layer(self):
        """Resuelve el objeto QgsVectorLayer real a partir del id guardado
        en el combo. Nunca guardamos el objeto capa directamente para evitar
        crashes si la capa es eliminada del proyecto mientras el diálogo
        sigue abierto."""
        layer_id = self.mMapLayerComboBox.currentData()
        if not layer_id:
            return None
        return QgsProject.instance().mapLayer(layer_id)

    def populate_field_table(self, layer):
        """Se dispara cada vez que el usuario cambia de capa."""
        self.populate_extra_layers_table()
        self.tableFieldMapping.blockSignals(True)
        self.tableFieldMapping.setRowCount(0)

        if layer is None:
            self.tableFieldMapping.blockSignals(False)
            return

        # Valores por defecto
        self.lineEditDocumentName.setText(layer.name())
        self.lineEditFolderName.setText(layer.name())

        fields = layer.fields()

        self.comboCampoLotes.clear()
        self.comboCampoCarpetas.clear()
        for field in fields:
            self.comboCampoLotes.addItem(field.name())
            self.comboCampoCarpetas.addItem(field.name())

        es_capa_de_puntos = layer.geometryType() == QgsWkbTypes.PointGeometry
        self.groupBoxIconosClasicos.setVisible(es_capa_de_puntos)
        if es_capa_de_puntos:
            self.checkBoxIconosClasicos.setChecked(True)

        self.tableFieldMapping.setColumnCount(5)
        self.tableFieldMapping.setHorizontalHeaderLabels(
            ["Campo original", "Nuevo nombre", "Kml/Name", "Kml/Description", "Exportar"])
        self.tableFieldMapping.setRowCount(len(fields))

        for row, field in enumerate(fields):
            item_original = QTableWidgetItem(field.name())
            item_original.setFlags(item_original.flags() & ~Qt.ItemIsEditable)
            self.tableFieldMapping.setItem(row, 0, item_original)

            item_new = QTableWidgetItem(field.name())
            self.tableFieldMapping.setItem(row, 1, item_new)

            item_name = QTableWidgetItem()
            item_name.setFlags(Qt.ItemIsUserCheckable | Qt.ItemIsEnabled)
            item_name.setCheckState(Qt.Unchecked)
            self.tableFieldMapping.setItem(row, 2, item_name)

            item_desc = QTableWidgetItem()
            item_desc.setFlags(Qt.ItemIsUserCheckable | Qt.ItemIsEnabled)
            item_desc.setCheckState(Qt.Unchecked)
            self.tableFieldMapping.setItem(row, 3, item_desc)

            # Columna 4: incluir en SchemaData, marcada por defecto
            item_include = QTableWidgetItem()
            item_include.setFlags(Qt.ItemIsUserCheckable | Qt.ItemIsEnabled)
            item_include.setCheckState(Qt.Checked)
            self.tableFieldMapping.setItem(row, 4, item_include)

        self.tableFieldMapping.blockSignals(False)

    def on_table_item_changed(self, item):
        """Asegura que solo una fila tenga marcada la columna Name,
        y solo una fila tenga marcada la columna Description."""
        column = item.column()

        if column not in (2, 3):
            return  # solo nos interesan las columnas de checkboxes

        if item.checkState() != Qt.Checked:
            return  # solo actuamos cuando se MARCA una casilla, no al desmarcar

        self.tableFieldMapping.blockSignals(True)
        for row in range(self.tableFieldMapping.rowCount()):
            if row != item.row():
                other_item = self.tableFieldMapping.item(row, column)
                if other_item is not None:
                    other_item.setCheckState(Qt.Unchecked)
        self.tableFieldMapping.blockSignals(False)

    def toggle_incluir_todo(self):
        """Marca todo si hay al menos una fila sin marcar; si no, desmarca todo."""
        total_rows = self.tableFieldMapping.rowCount()
        if total_rows == 0:
            return

        # Revisar si falta alguna por marcar
        hay_alguna_desmarcada = False
        for row in range(total_rows):
            item = self.tableFieldMapping.item(row, 4)
            if item is not None and item.checkState() != Qt.Checked:
                hay_alguna_desmarcada = True
                break

        nuevo_estado = Qt.Checked if hay_alguna_desmarcada else Qt.Unchecked

        self.tableFieldMapping.blockSignals(True)
        for row in range(total_rows):
            item = self.tableFieldMapping.item(row, 4)
            if item is not None:
                item.setCheckState(nuevo_estado)
        self.tableFieldMapping.blockSignals(False)

    def get_name_field(self):
        """Devuelve el nombre del campo original marcado como Name, o None."""
        for row in range(self.tableFieldMapping.rowCount()):
            item = self.tableFieldMapping.item(row, 2)
            if item is not None and item.checkState() == Qt.Checked:
                return self.tableFieldMapping.item(row, 0).text()
        return None

    def get_description_field(self):
        """Devuelve el nombre del campo original marcado como Description, o None."""
        for row in range(self.tableFieldMapping.rowCount()):
            item = self.tableFieldMapping.item(row, 3)
            if item is not None and item.checkState() == Qt.Checked:
                return self.tableFieldMapping.item(row, 0).text()
        return None

    def get_field_mapping(self):
        """Devuelve un dict {nombre_original: nombre_nuevo}
        solo para los campos marcados como incluidos."""
        mapping = {}
        for row in range(self.tableFieldMapping.rowCount()):
            include_item = self.tableFieldMapping.item(row, 4)
            if include_item is None or include_item.checkState() != Qt.Checked:
                continue  # el usuario excluyó este campo

            original = self.tableFieldMapping.item(row, 0).text()
            new_name = self.tableFieldMapping.item(row, 1).text().strip()
            mapping[original] = new_name if new_name else original
        return mapping

    def select_output_path(self):
        if self.checkBoxExportarPorLotes.isChecked():
            folder = QFileDialog.getExistingDirectory(self, "Selecciona la carpeta de salida")
            if folder:
                self.lineEditOutputPath.setText(folder)
        else:
            path, _ = QFileDialog.getSaveFileName(
                self, "Guardar como KML", "", "KML Files (*.kml)")
            if path:
                if not path.lower().endswith('.kml'):
                    path += '.kml'
                self.lineEditOutputPath.setText(path)

    def run_export(self):
        layer = self._get_current_layer()

        if layer is None:
            QMessageBox.warning(self, "Aviso", "Selecciona una capa.")
            return

        output_path = self.lineEditOutputPath.text().strip()
        document_name = self.lineEditDocumentName.text().strip()
        folder_name = self.lineEditFolderName.text().strip()

        if not document_name:
            document_name = layer.name()
        if not folder_name:
            folder_name = layer.name()

        if not output_path:
            QMessageBox.warning(self, "Aviso", "Selecciona una ruta de salida.")
            return

        field_mapping = self.get_field_mapping()
        name_field = self.get_name_field()
        description_field = self.get_description_field()

        # Caso 1: no hay absolutamente nada que exportar
        if not field_mapping and name_field is None and description_field is None:
            QMessageBox.warning(
                self, "Aviso",
                "No hay nada que exportar. Marca un campo como Name/Description "
                "o incluye al menos un campo en la tabla de atributos."
            )
            return

        # Caso 2: hay tabla pero no Name/Description -> avisar y confirmar
        if name_field is None and description_field is None:
            respuesta = QMessageBox.question(
                self, "Aviso",
                "No marcaste ningún campo como Name ni como Description.\n"
                "Se exportará solo la tabla de atributos (SchemaData), sin "
                "título ni descripción en los globos.\n\n¿Deseas continuar?",
                QMessageBox.Yes | QMessageBox.No
            )
            if respuesta == QMessageBox.No:
                return

        # Caso 3: hay Name y/o Description pero no hay tabla -> avisar y confirmar
        if not field_mapping and (name_field is not None or description_field is not None):
            respuesta = QMessageBox.question(
                self, "Aviso",
                "No incluiste campos en la tabla de atributos (SchemaData).\n"
                "Se exportará solo Name/Description, sin tabla.\n\n¿Deseas continuar?",
                QMessageBox.Yes | QMessageBox.No
            )
            if respuesta == QMessageBox.No:
                return

        group_field = None
        reference_layer = None
        reference_name_field = None
        if self.checkBoxAgruparCarpetas.isChecked():
            group_field = self.comboCampoCarpetas.currentText()
            if not group_field:
                QMessageBox.warning(self, "Aviso", "Selecciona el campo de agrupación.")
                return
            if self.checkBoxCapaReferencia.isChecked():
                ref_id = self.comboCapaReferencia.currentData()
                reference_layer = QgsProject.instance().mapLayer(ref_id) if ref_id else None
                if reference_layer is None:
                    QMessageBox.warning(self, "Aviso", "Selecciona la capa de referencia.")
                    return
                reference_name_field = self.comboCampoReferencia.currentText() or None

        usar_iconos_clasicos = (
            self.checkBoxIconosClasicos.isVisible()
            and self.checkBoxIconosClasicos.isChecked()
        )

        omitir_vacios = self.checkBoxOmitirVacios.isChecked()
        extra_layers = self.get_extra_layers()

        try:
            if self.checkBoxExportarPorLotes.isChecked():
                from .kml_export_logic import export_layer_to_kml_batch
                batch_field = self.comboCampoLotes.currentText()
                generated = export_layer_to_kml_batch(
                    layer, field_mapping, output_path, batch_field,
                    name_field=name_field,
                    description_field=description_field,
                    usar_iconos_clasicos=usar_iconos_clasicos,
                    group_field=group_field,
                    reference_layer=reference_layer,
                    reference_name_field=reference_name_field,
                    omitir_vacios=omitir_vacios
                )
                QMessageBox.information(
                    self, "Éxito",
                    f"Se generaron {len(generated)} archivos KML en:\n{output_path}")
            else:
                from .kml_export_logic import export_layer_to_kml
                export_layer_to_kml(
                    layer,
                    field_mapping,
                    output_path,
                    name_field=name_field,
                    description_field=description_field,
                    document_name=document_name,
                    folder_name=folder_name,
                    usar_iconos_clasicos=usar_iconos_clasicos,
                    group_field=group_field,
                    reference_layer=reference_layer,
                    reference_name_field=reference_name_field,
                    omitir_vacios=omitir_vacios,
                    extra_layers=extra_layers
                )
                QMessageBox.information(
                    self, "Éxito", f"Exportado correctamente a:\n{output_path}")
            self.accept()
        except Exception as e:
            QMessageBox.critical(self, "Error", f"Falló la exportación:\n{str(e)}")